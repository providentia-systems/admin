import 'dart:math';

/// Returns whether [value] is a canonical RFC 9562 UUID.
///
/// Providentia creates client intent identifiers as UUIDv4 while the Backend
/// creates durable entity identifiers as UUIDv7. Keep validation deliberately
/// broader than generation so both sides of that contract remain compatible.
bool isUuid(String value) => _uuidPattern.hasMatch(value);

String newUuidV4() {
  final random = Random.secure();
  final bytes = List<int>.generate(16, (_) => random.nextInt(256));
  bytes[6] = (bytes[6] & 0x0f) | 0x40;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  final hex = bytes
      .map((byte) => byte.toRadixString(16).padLeft(2, '0'))
      .join();
  return '${hex.substring(0, 8)}-${hex.substring(8, 12)}-'
      '${hex.substring(12, 16)}-${hex.substring(16, 20)}-'
      '${hex.substring(20)}';
}

final RegExp _uuidPattern = RegExp(
  r'^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$',
  caseSensitive: false,
);
